def interpolate_pts(coords: list[tuple[float, float]]):
    all_pts = []
    n = len(coords)

    # interpolate each pair
    for i in range(n - 1):
        (lat1, long1), (lat2, long2) = coords[i], coords[i+1]

        p1 = Point(lat1, long1)
        p2 = Point(lat2, long2)

        line = LineString([p1, p2])

        step = 0.05
        for h in np.arange(step, 1, step): # np.arange = 0.1, 0.2, 0.3 ...
            pt = line.interpolate(h, normalized=True)
            all_pts.append((pt.x, pt.y-0.0000005))

    return all_pts

